#!/bin/bash
# Обновить рабочие копии инструментов ($SP/tools) из репозитория: sync_tools.sh [каталог tools]  (по умолчанию $SP/tools)
# Только rsync: он пишет во временный файл и переименовывает (новый inode), поэтому уже запущенный скрипт дочитывает свою старую копию.
# Правка «на месте» (cp, sed -i, редактор) ломает работающий bash-скрипт — он читает файл по ходу выполнения (инцидент партии 3, 2026-09-08).
set -e; T=${1:-${SP:?задайте SP или каталог tools}/tools}; mkdir -p "$T"
rsync -a --exclude '__pycache__' /workspaces/schubert-lieder/planning/audio/scripts/ "$T/"; echo "инструменты обновлены: $T ($(ls "$T" | wc -l) файлов)"
