export const meta = {
  name: 'cycle-conventions',
  description: 'Нулевой шаг цикла: файл конвенций (сквозные образы, единые русские решения повторяющихся слов, тон) — opus по досье поэта и фактам цикла',
  phases: [{ title: 'Конвенции цикла' }],
}
// args = {cycles: [{id, title, poet, songs, out}]}
const REPO = '/workspaces/schubert-lieder'
const one = (c) => agent(`Ты — редактор проекта «все песни Шуберта с пословным русским переводом». Задача — ОДИН файл: конвенции перевода цикла «${c.title}» (${c.id}), ${REPO}/${c.out}. Это нулевой шаг перед переводом цикла: по нему потом будут работать переводчики всех ${c.songs} песен, поэтому он должен решать заранее то, что иначе разойдётся от песни к песне.

ЧТО ПРОЧИТАТЬ
1. Досье поэта: ${REPO}/planning/research/poets/${c.poet}.md — целиком.
2. Немецкие тексты цикла: ${REPO}/app/src/data/songs/ — файлы, где поле "d" начинается с «${c.id}» (найди их командой ls и прочитай ВСЕ; в них поле lines_de).
3. Закон агентов проекта: ${REPO}/planning/catalog/one-shot-brief.md и ${REPO}/docs/rules/style.md — тон и запреты.
4. Эталон готовой страницы для тона: ${REPO}/app/src/data/songs/d118-gretchen-am-spinnrade.json (раздел about и аннотации).

ЧТО РЕШИТЬ И ЗАПИСАТЬ (это и есть содержание файла)
— **Сквозные слова и образы**: выпиши те, что повторяются в разных песнях цикла (ручей, мельница, зелёный цвет, странствие, охотник, цветы, сердце, окно и прочее по факту текстов), с указанием, в каких песнях встречаются, и с ЕДИНЫМ русским решением для каждого. Именно единство важнее изящества: одно немецкое слово в цикле должно переводиться одинаково всюду, где значит одно и то же, а расхождения — оговариваться.
— **Обращения и лица**: как передаём du/ihr к ручью, к мельнице, к возлюбленной; где меняется адресат.
— **Ключевые повторы и рефрены**: строки и формулы, возвращающиеся в разных песнях, — единая передача.
— **Тон**: чего в этом цикле НЕ делать по-русски (например, не сглаживать простоту народной песни книжностью), с двумя-тремя примерами «так — не так».
— **Спорные места**: слова, которые придётся решать индивидуально, с указанием, что решение принимает переводчик песни и оговаривает в сноске.

ТРЕБОВАНИЯ
— Каждое утверждение о цикле (сюжет, композиция, датировка, история) — только с опорой на досье поэта или на текст самих песен; литературоведческих домыслов не добавлять.
— Никаких выдуманных немецких слов: сквозные слова выписывай из lines_de, проверяя по файлам.
— Файл — рабочий инструмент, а не эссе: списки и таблицы, коротко.
— Результат — ОДИН вызов Write по указанному пути. В репозиторий больше ничего не писать, субагентов не спавнить.
Верни по схеме: id="${c.id}", ok, n_words (сколько сквозных слов выписано), n_songs_read, tool_calls.`, {
  label: `конвенции ${c.id}`, phase: 'Конвенции цикла', model: 'opus', effort: 'high',
  schema: { type: 'object', properties: { id: { type: 'string' }, ok: { type: 'boolean' }, n_words: { type: 'number' }, n_songs_read: { type: 'number' }, tool_calls: { type: 'number' } }, required: ['id', 'ok', 'tool_calls'] },
})
const res = await parallel(args.cycles.map((c) => () => one(c)))
return { res }
